 * 시작 좌표에서 가장 가까운 시드 클러스터의 장소들을 공급한다.
 * 클러스터는 서비스 지역인 수도권 6곳(서울·인천·수원·가평·파주·용인).
 * 장소마다 tags 태그(산/바다/공원/강/실내/온천 등)를 부여해 취향 필터가 동작한다.
 * 좌표는 실제 지명 기준의 근사값, 가격·평점은 현실적인 추정치다.
 */
@Service
class SeedPlaceService {

    private val log = LoggerFactory.getLogger(SeedPlaceService::class.java)
    private val idSeq = AtomicLong(5_000_000)

    data class Cluster(
        val name: String,
        val centerLat: Double,
        val centerLng: Double,
        val lodgings: List<Place>,
        val restaurants: List<Place>,
        val attractions: List<Place>,
    )

    private fun p(
        name: String, type: PlaceType, address: String,
        lat: Double, lng: Double, price: Int, rating: Double, desc: String,
        vararg tags: String,
    ): Place = Place(name, type, address, lat, lng, price, rating, desc)
        .also { it.tags = tags.toSet() }

    private val clusters: List<Cluster> = buildClusters()

    /** 시작 좌표에서 가장 가까운 시드 클러스터의 장소 풀 (장소마다 새 id 부여) */
    fun poolNear(lat: Double, lng: Double): SeedPool {
        val cluster = clusters.minByOrNull {
            GeoUtil.distanceMeters(lat, lng, it.centerLat, it.centerLng)
        }!!
        log.info("시드 장소 폴백 사용: {} 클러스터 (숙박 {}, 식당 {}, 관광 {})",
            cluster.name, cluster.lodgings.size, cluster.restaurants.size, cluster.attractions.size)
        return SeedPool(
            cluster.name,
            cluster.lodgings.map { copyWithId(it) },
            cluster.restaurants.map { copyWithId(it) },
            cluster.attractions.map { copyWithId(it) },
        )
    }

    data class SeedPool(
        val region: String,
        val lodgings: List<Place>,
        val restaurants: List<Place>,
        val attractions: List<Place>,
    )

    private fun copyWithId(src: Place): Place =
        Place(src.name, src.type, src.address, src.latitude, src.longitude,
            src.price, src.rating, src.description).also {
            it.id = idSeq.incrementAndGet()
            it.tags = src.tags
        }

